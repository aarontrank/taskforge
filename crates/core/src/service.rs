    #[test]
    fn a_refused_transition_fires_no_hook() {
        let d = tempfile::tempdir().unwrap();
        let out = d.path().join("fired");
        let engine = crate::hooks::HookEngine::new(vec![crate::hooks::HookConfig {
            id: "capture".into(),
            enabled: true,
            event: "task.status_changed".into(),
            command: "sh".into(),
            args: vec!["-c".into(), format!("cat >> {}", out.display())],
            workspace_filter: None,
            timeout_ms: 5_000,
        }]);
        let mut s = TaskService::new(MemoryStore::new(), "2026-09-02T00:00:00Z").with_hooks(engine);
        s.store.put(task("TASK-0001")).unwrap(); // Open

        // Open -> Merged is illegal, so nothing was committed and nothing should be announced.
        assert!(s
            .set_status("TASK-0001", TaskStatus::Merged, "aaron", None)
            .is_err());
        assert!(
            !out.exists(),
            "no hook may fire for a mutation that did not happen"
        );
    }

    #[test]
    fn a_failing_hook_does_not_roll_back_the_status_change() {
        let engine = crate::hooks::HookEngine::new(vec![crate::hooks::HookConfig {
            id: "bad".into(),
            enabled: true,
            event: "task.status_changed".into(),
            command: "false".into(),
            args: vec![],
            workspace_filter: None,
            timeout_ms: 5_000,
        }]);
        let mut s = TaskService::new(MemoryStore::new(), "2026-09-02T00:00:00Z").with_hooks(engine);
        s.store.put(task("TASK-0001")).unwrap();

        let out = s.set_status("TASK-0001", TaskStatus::Running, "aaron", None);
        assert!(
            out.is_ok(),
            "the mutation stands: hooks are notifications, not gates"
        );
        assert_eq!(
            s.store.get("TASK-0001").unwrap().status,
            TaskStatus::Running
        );
        assert_eq!(s.last_hook_results.len(), 1);
        assert!(!s.last_hook_results[0].ok, "but the failure is reported");
    }

    #[test]
    fn a_failed_task_write_is_reported_rather_than_reported_as_success() {
        // The defect this covers: `put` used to return `()`, so a full disk or a read-only
        // mount produced `ok: true` with a bumped version while the file on disk never moved.
        let mut s = svc();
        s.store.put(task("TASK-0001")).unwrap();
        s.store.fail_writes_now();

        let err = s
            .set_status("TASK-0001", TaskStatus::Running, "agent", None)
            .unwrap_err();
        assert_eq!(err.code(), "IO_ERROR", "got: {err}");
    }

