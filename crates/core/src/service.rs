/// A domain error, carrying the stable code the CLI reports in its JSON envelope.
#[derive(Debug, thiserror::Error)]
pub enum TaskError {
    #[error("task not found: {0}")]
    NotFound(String),
    #[error("cannot move {id} from {from} to {to}")]
    InvalidTransition {
        id: String,
        from: TaskStatus,
        to: TaskStatus,
    },
    #[error("{id} is blocked by unresolved task(s): {blockers}")]
    Blocked { id: String, blockers: String },
    #[error("{0} requires review; request review instead of completing it directly")]
    ReviewRequired(String),
    #[error("{id} is at version {actual}, not {expected}; re-read and retry")]
    VersionMismatch {
        id: String,
        expected: i64,
        actual: i64,
    },
    #[error("could not write {id}: {source}")]
    Io { id: String, source: std::io::Error },
}

impl TaskError {
    /// The stable machine-readable code. Kept identical to the documented set so existing
    /// agent error handling keeps working across the rewrite.
    pub fn code(&self) -> &'static str {
        match self {
            TaskError::NotFound(_) => "TASK_NOT_FOUND",
            TaskError::InvalidTransition { .. } => "INVALID_STATUS_TRANSITION",
            TaskError::Blocked { .. } => "BLOCKED_BY_OPEN_TASK",
            TaskError::ReviewRequired(_) => "REVIEW_REQUIRED",
            TaskError::VersionMismatch { .. } => "CONFLICT_VERSION_MISMATCH",
            TaskError::Io { .. } => "IO_ERROR",
        }
    }
}

/// A problem that happened *after* a mutation was already committed.
///
/// It cannot be an error — the change is real and the caller must be told it happened — but it
/// must not be silent either, or an agent believes a notification fired or an audit entry
/// landed when neither did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Warning {
    pub code: &'static str,
    pub message: String,
}

/// Workflow operations over a store.
///
/// `now` is injected rather than read from the clock so every timestamp assertion in the
/// tests is exact instead of approximate.
pub struct TaskService<S: TaskStore> {
    pub store: S,
    now: String,
    /// Id of the occurrence generated by the most recent completion, if any. Recorded so a
    /// caller (and the tests) can report the follow-on task without re-scanning the store.
    pub last_generated: Option<String>,
    /// Hooks to announce committed mutations to. `None` means none are configured, which is
    /// the common case and must stay free of cost.
    hooks: Option<HookEngine>,
    /// Outcome of the hooks fired by the most recent mutation. The CLI turns any failure among
    /// these into an envelope warning.
    pub last_hook_results: Vec<HookResult>,
    /// Post-commit problems from the most recent mutation, for the caller to report.
    pub last_warnings: Vec<Warning>,
}

impl<S: TaskStore> TaskService<S> {
    pub fn new(store: S, now: impl Into<String>) -> Self {
        TaskService {
            store,
            now: now.into(),
            last_generated: None,
            hooks: None,
            last_hook_results: Vec::new(),
            last_warnings: Vec::new(),
        }
    }

    /// Attach a hook engine. Hooks fire only after a mutation is committed, and never gate it.
    pub fn with_hooks(mut self, engine: HookEngine) -> Self {
        self.hooks = Some(engine);
        self
    }

    /// Move a task to a new status, enforcing the transition table, blockers, the review
    /// gate, and optimistic concurrency — in that order, so the most specific complaint wins.
    pub fn set_status(
        &mut self,
        id: &str,
        to: TaskStatus,
        actor: &str,
        expected_version: Option<i64>,
    ) -> Result<Task, TaskError> {
        let mut task = self
            .store
            .get(id)
            .ok_or_else(|| TaskError::NotFound(id.to_string()))?;

        if let Some(expected) = expected_version {
            if expected != task.version {
                return Err(TaskError::VersionMismatch {
                    id: id.to_string(),
                    expected,
                    actual: task.version,
                });
            }
        }

        let from = task.status;
        if !can_transition(from, to) {
            return Err(TaskError::InvalidTransition {
                id: id.to_string(),
                from,
                to,
            });
        }

        // Completing without review is only legitimate when no review was demanded.
        if to == TaskStatus::Done && task.review_required && from != TaskStatus::Merged {
            return Err(TaskError::ReviewRequired(id.to_string()));
        }

        // Dispatching work requires every dependency to be genuinely finished. `Merged` does
        // not qualify: it still awaits acceptance.
        if to == TaskStatus::Running {
            let unresolved: Vec<String> = task
                .blocked_by
                .iter()
                .filter(|b| {
                    self.store
                        .get(b)
                        .map(|t| t.status != TaskStatus::Done)
                        .unwrap_or(true)
                })
                .cloned()
                .collect();
            if !unresolved.is_empty() {
                return Err(TaskError::Blocked {
                    id: id.to_string(),
                    blockers: unresolved.join(", "),
                });
            }
        }

        task.status = to;
        task.updated_at = self.now.clone();
        task.version += 1;
        match to {
            TaskStatus::Done => task.completed_at = Some(self.now.clone()),
            TaskStatus::InReview => task.review_requested_at = Some(self.now.clone()),
            _ => {}
        }

        self.last_warnings.clear();

        // The one write whose failure is fatal: until this lands, nothing has happened, and
        // reporting success would hand the caller a status that is not stored.
        self.store.put(task.clone()).map_err(|e| TaskError::Io {
            id: id.to_string(),
            source: e,
        })?;

        // Everything below runs after the change is committed, so no failure here can un-commit
        // it. Each is therefore a warning: real, reported, and not an error.
        if let Err(e) = self.store.append_audit(AuditEntry {
            ts: self.now.clone(),
            actor: actor.to_string(),
            action: "status_changed".to_string(),
            task_id: id.to_string(),
            from: Some(from.to_string()),
            to: Some(to.to_string()),
        }) {
            self.last_warnings.push(Warning {
                code: "AUDIT_WRITE_FAILED",
                message: format!("{id} moved to {to} but the audit entry was not written: {e}"),
            });
        }

        self.last_hook_results = match &self.hooks {
            Some(engine) => engine.fire("task.status_changed", &task.workspace, id, to.as_str()),
            None => Vec::new(),
        };

        // A recurring task that reaches Done spawns its successor, so "later" is scheduled
        // rather than remembered.
        self.last_generated = None;
        if to == TaskStatus::Done {
            if let Some(rec) = task.recurrence.clone() {
                match self.generate_next_occurrence(&task, &rec, actor) {
                    Ok(next) => self.last_generated = Some(next),
                    Err(e) => self.last_warnings.push(Warning {
                        code: "RECURRENCE_WRITE_FAILED",
                        message: format!(
                            "{id} completed but its next occurrence was not created: {e}"
                        ),
                    }),
                }
            }
        }
        Ok(task)
    }

    /// Create the follow-on occurrence of a completed recurring task.
    ///
    /// Fallible so a failure to store the successor is reported rather than announced as an id
    /// that was never written.
    fn generate_next_occurrence(
        &mut self,
        prior: &Task,
        rec: &Recurrence,
        actor: &str,
    ) -> std::io::Result<String> {
        let id = self.store.allocate_id();
        let mut next = Task::new(
            &id,
            &prior.title,
            &prior.workspace,
            &prior.owner,
            self.now.clone(),
        );

        if rec.carry_forward_description {
            next.description = prior.description.clone();
        }
        if rec.preserve_review_required {
            next.review_required = prior.review_required;
            next.reviewer = prior.reviewer.clone();
        }
        if !rec.carry_forward_owner {
            next.owner = String::new();
        }
        next.prior_occurrence_id = Some(prior.id.clone());
        // The schedule itself carries forward, or the task would recur exactly once.
        next.recurrence = Some(rec.clone());
        next.due_at = self.next_due(prior, rec);

        self.store.put(next)?;
        self.store.append_audit(AuditEntry {
            ts: self.now.clone(),
            actor: actor.to_string(),
            action: "recurrence_generated".to_string(),
            task_id: id.clone(),
            from: Some(prior.id.clone()),
            to: None,
        })?;
        Ok(id)
    }

    /// Due date for the next occurrence, per the configured strategy.
    ///
    /// `None` means "do not carry a due date forward" and is also the answer when the prior
    /// task had no due date to advance, or when its timestamp cannot be parsed — an
    /// unparseable date must not become a panic in the middle of a completion.
    fn next_due(&self, prior: &Task, rec: &Recurrence) -> Option<String> {
        if rec.carry_forward_due_strategy == DueStrategy::None {
            return None;
        }
        let prior_due = prior.due_at.as_deref()?;
        let base = match rec.carry_forward_due_strategy {
            DueStrategy::Relative => &self.now,
            _ => prior_due,
        };
        advance(base, rec.frequency, rec.interval)
    }
}

/// Add `interval` periods of `frequency` to an RFC3339 timestamp.
///
/// Month arithmetic clamps to the last valid day of the target month: 31 January plus one
/// month is 28 February, not 3 March. JavaScript's `setMonth` overflows instead, so this is a
/// deliberate divergence from the implementation being replaced — silently skipping a month is
/// a worse answer for a recurring task than landing on its final day.
fn advance(ts: &str, freq: RecurrenceFrequency, interval: u32) -> Option<String> {
    use time::format_description::well_known::Rfc3339;
    let start = time::OffsetDateTime::parse(ts, &Rfc3339).ok()?;
    let n = interval as i64;
    let moved = match freq {
        RecurrenceFrequency::Hourly => start.checked_add(time::Duration::hours(n))?,
        RecurrenceFrequency::Daily => start.checked_add(time::Duration::days(n))?,
        RecurrenceFrequency::Weekly => start.checked_add(time::Duration::weeks(n))?,
        RecurrenceFrequency::Monthly => {
            let months_total = start.month() as i32 - 1 + interval as i32;
            let year = start.year() + months_total / 12;
            let month = time::Month::try_from((months_total % 12 + 1) as u8).ok()?;
            let last = time::util::days_in_month(month, year);
            let day = start.day().min(last);
            // Step to day 1 before changing month: replacing the month while the day is
            // still 31 is rejected outright for a short target month.
            start
                .replace_day(1)
                .ok()?
                .replace_year(year)
                .ok()?
                .replace_month(month)
                .ok()?
                .replace_day(day)
                .ok()?
        }
    };
    moved.format(&Rfc3339).ok()
}

