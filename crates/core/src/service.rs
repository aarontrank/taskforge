    fn recurring(
        id: &str,
        freq: RecurrenceFrequency,
        due: Option<&str>,
        strat: DueStrategy,
    ) -> Task {
        let mut t = task(id);
        t.status = TaskStatus::Running;
        t.due_at = due.map(String::from);
        t.recurrence = Some(Recurrence {
            frequency: freq,
            interval: 1,
            preserve_review_required: true,
            carry_forward_description: true,
            carry_forward_owner: true,
            carry_forward_due_strategy: strat,
        });
        t
    }

    #[test]
    fn completing_a_recurring_task_generates_a_linked_next_occurrence() {
        let mut s = svc();
        let mut t = recurring(
            "TASK-0001",
            RecurrenceFrequency::Daily,
            None,
            DueStrategy::None,
        );
        t.description = Some("water the plants".into());
        s.store.put(t).unwrap();

        let done = s
            .set_status("TASK-0001", TaskStatus::Done, "aaron", None)
            .unwrap();
        assert_eq!(done.status, TaskStatus::Done);

        let next = s
            .last_generated
            .clone()
            .expect("a next occurrence was created");
        let n = s.store.get(&next).expect("and stored");
        assert_ne!(n.id, "TASK-0001", "it is a new task");
        assert_eq!(
            n.prior_occurrence_id.as_deref(),
            Some("TASK-0001"),
            "linked to its predecessor"
        );
        assert_eq!(
            n.status,
            TaskStatus::Open,
            "the new occurrence starts fresh"
        );
        assert_eq!(
            n.description.as_deref(),
            Some("water the plants"),
            "description carried"
        );
        assert!(
            n.recurrence.is_some(),
            "the schedule carries forward, or it recurs once"
        );
    }

